@dataclass
class SpeculativeResult:
    """Result of a speculative generation run."""
    final_response: str
    draft_response: str
    verify_response: str
    draft_model: str
    verify_model: str
    draft_accepted: bool
    iterations: int
    total_latency_ms: float
    draft_latency_ms: float
    verify_latency_ms: float
    convergence_score: float


# ---------------------------------------------------------------------------
# Convergence / similarity utilities
# ---------------------------------------------------------------------------


def compute_similarity(text_a: str, text_b: str) -> float:
    """Compute heuristic similarity between two texts.

    Uses word overlap (Jaccard similarity) combined with length ratio
    to estimate how similar two responses are.

    Args:
        text_a: First text.
        text_b: Second text.

    Returns:
        Similarity score between 0.0 and 1.0.
    """
    if not text_a or not text_b:
        return 0.0

    words_a = set(text_a.lower().split())
    words_b = set(text_b.lower().split())

    if not words_a or not words_b:
        return 0.0

    # Jaccard similarity
    intersection = words_a & words_b
    union = words_a | words_b
    jaccard = len(intersection) / len(union) if union else 0.0

    # Length ratio penalty
    len_a = len(text_a)
    len_b = len(text_b)
    length_ratio = min(len_a, len_b) / max(len_a, len_b) if max(len_a, len_b) > 0 else 0.0

    # Combined score (weighted)
    return 0.7 * jaccard + 0.3 * length_ratio


